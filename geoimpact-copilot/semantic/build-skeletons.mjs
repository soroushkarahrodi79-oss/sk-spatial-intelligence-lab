#!/usr/bin/env node
// Regenerates the reviewed narrative vocabulary (approved-skeletons.json).
//
// A "skeleton" is a claim's text with every field-bound span replaced by {{field}}. The
// verifier accepts a claim only if its skeleton is in this file, so a changed sentence
// in answer.mjs, or any sentence a future provider adds, fails closed until a human
// reviews the diff of this file. Run with --check to confirm the committed file matches.
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { answerQuestion } from "../lib/answer.mjs";
import { loadReportFile } from "../lib/report.mjs";
import { analyzeClaim, normalizeClaimId } from "../lib/semantic.mjs";
import { generateReports, range } from "../evaluation/synthetic/generator.mjs";
import { questions } from "../evaluation/oracle.mjs";

const here = new URL("./", import.meta.url);
const registryUrl = new URL("./approved-skeletons.json", here);
const fixtureNames = [
  "block-v5.json",
  "pass-v5.json",
  "generated-v1.2.0/report-v4-block.json",
  "generated-v1.2.0/report-v5-block.json",
  "generated-v1.2.0/report-v5-pass.json"
];
const topicWords = ["provenance", "relationship", "area", "feature", "verdict"];
const topicCombinations = Array.from({ length: 2 ** topicWords.length }, (_, mask) => topicWords.filter((_, bit) => mask & (1 << bit)))
  .filter((words) => words.length > 1)
  .map((words) => `What about ${words.join(" and ")}?`);
const extraQuestions = [...topicCombinations, "", "What engine versions are listed in provenance?", "Which source datasets are named in this report?", "What is the maximum boundary displacement?"];

function conditionsFor(normalizedId, report, skeleton) {
  if (normalizedId === "relationship-limits" && skeleton.startsWith("No changed")) {
    return ["no_regressions", report.primary_change.changed_feature_ids.length > 0 ? "primary_changed" : "no_primary_changed"];
  }
  if (normalizedId === "relationship-limits") return ["has_regressions"];
  if (normalizedId === "provenance-datasets") return [report.analysis.dependencies.length > 0 ? "has_dependencies" : "no_dependencies"];
  return [];
}

export async function collectReports() {
  const reports = [];
  for (const name of fixtureNames) reports.push(await loadReportFile(fileURLToPath(new URL(`../fixtures/${name}`, here))));
  // The development split only. Held-out reports are never used to build the vocabulary.
  for (const { report } of generateReports(range(1, 60))) reports.push(report);
  for (const overrides of [{ dependency_count: 0, regression_count: 0, unchanged_relationship_count: 0 }, { regression_count: 0, primary_changed: true }, { regression_count: 0, primary_changed: false }]) {
    for (const { report } of generateReports(range(500, 4), overrides)) reports.push(report);
  }
  return reports;
}

export const allQuestions = () => [...questions.map((item) => item.question), ...extraQuestions];

export async function collectSkeletons() {
  const reports = await collectReports();
  const claims = new Map();
  for (const report of reports) {
    for (const question of [...questions.map((item) => item.question), ...extraQuestions]) {
      const answer = answerQuestion(report, question, { registry: false });
      for (const claim of answer.claims) {
        const { skeleton, errors } = analyzeClaim(claim, report);
        if (errors.length) throw new Error(`${claim.id}: ${errors[0]}`);
        const id = normalizeClaimId(claim.id);
        const when = conditionsFor(id, report, skeleton);
        const key = `${id}\u0000${skeleton}\u0000${when.join(",")}`;
        claims.set(key, { id, skeleton, when });
      }
    }
  }
  const grouped = {};
  for (const { id, skeleton, when } of [...claims.values()].sort((a, b) => a.id.localeCompare(b.id) || a.skeleton.localeCompare(b.skeleton))) {
    (grouped[id] ??= []).push(when.length ? { skeleton, when } : { skeleton });
  }
  let review = { status: "unreviewed", reviewed_by: null, reviewed_on: null, note: "Generated vocabulary. No person has confirmed these sentences. Review with docs/geoimpact-v0.2-human-review-checklist.md; the gate enforces the vocabulary regardless of review status." };
  try {
    review = JSON.parse(await readFile(registryUrl, "utf8")).review ?? review;
  } catch { /* first build */ }
  return { version: 1, review, note: "Generated by build-skeletons.mjs. Review every change: this file is the closed set of sentences a claim may contain.", claims: grouped };
}

if (process.argv[1] && fileURLToPath(import.meta.url) === fileURLToPath(new URL(`file://${process.argv[1].replaceAll("\\", "/")}`))) {
  const registry = `${JSON.stringify(await collectSkeletons(), null, 2)}\n`;
  if (process.argv.includes("--check")) {
    const current = await readFile(registryUrl, "utf8");
    if (current !== registry) {
      process.stderr.write("approved-skeletons.json is out of date; run node geoimpact-copilot/semantic/build-skeletons.mjs and review the diff.\n");
      process.exitCode = 1;
    } else {
      process.stdout.write("approved-skeletons.json matches the generated vocabulary.\n");
    }
  } else {
    await writeFile(registryUrl, registry);
    process.stdout.write(`Wrote ${fileURLToPath(registryUrl)}\n`);
  }
}
