#!/usr/bin/env node
// Generates the human-review checklist for every sentence the semantic gate allows.
// The checklist is a worksheet, not a certificate: it is generated with every box
// unchecked and every decision blank, and nothing in this repository fills them in.
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { answerQuestion } from "../lib/answer.mjs";
import { analyzeClaim, normalizeClaimId, numericContracts, stringContracts } from "../lib/semantic.mjs";
import { allQuestions, collectReports } from "./build-skeletons.mjs";

const registryUrl = new URL("./approved-skeletons.json", import.meta.url);
const outputUrl = new URL("../../docs/geoimpact-v0.2-human-review-checklist.md", import.meta.url);

const flagRules = [
  ["geographic", /\b(district|region|city|country|location|located|place names?|geograph\w*|administrative|map|coordinates?)\b/i],
  ["temporal", /\b(timestamps?|dates?|recent\w*|years?|during|when|acquisition)\b/i],
  ["causal", /\b(cause[sd]?|causal|because|due to|leads? to|result\w*|impact|effects?|harm\w*|outcome)\b/i],
  ["legal", /\b(legal|licen[cs]e|rights?|law|regulat\w*)\b/i],
  ["scientific", /\b(accura\w*|uncertain\w*|confidence|calibrat\w*|significan\w*|semantics|positional|correct\w*|spatial|geometric)\b/i]
];

function flagsFor(skeleton) {
  const constant = skeleton.replace(/\{\{[^}]+\}\}/g, " ");
  const flags = flagRules.filter(([, pattern]) => pattern.test(constant)).map(([name]) => name);
  const negated = /\b(not|no|cannot|does not|do not|without)\b/i.test(constant);
  return { flags, negated };
}

function slotLabel(id) {
  const numeric = numericContracts.find((contract) => contract.id === id);
  if (numeric) return `${numeric.lead.trim()} … ${numeric.unit} (${numeric.path ?? numeric.source_path})`;
  const string = stringContracts.find((contract) => contract.id === id);
  return string ? `${string.label} (${string.test.source.replace(/\\\//g, "/").replace(/^\^|\$$/g, "")})` : id;
}

export async function buildChecklist() {
  const registry = JSON.parse(await readFile(registryUrl, "utf8"));
  const sources = new Map();
  for (const report of await collectReports()) {
    for (const question of allQuestions()) {
      const answer = answerQuestion(report, question, { registry: false });
      for (const claim of answer.claims) {
        const { skeleton } = analyzeClaim(claim, report);
        const key = `${normalizeClaimId(claim.id)}\u0000${skeleton}`;
        const set = sources.get(key) ?? new Map();
        for (const reference of claim.references.filter((item) => item.type === "source_record")) {
          set.set(`${reference.source_id}#${reference.fact_key}`, reference);
        }
        sources.set(key, set);
      }
    }
  }
  const lines = [
    "# GeoImpact Evidence Copilot V0.2: human-review checklist",
    "",
    "**Review status: UNREVIEWED.** This file is generated by `geoimpact-copilot/semantic/build-review-checklist.mjs` from `approved-skeletons.json`. Every box is unchecked and every decision is blank. No person has confirmed any sentence below, and no automated process in this repository may fill the fields in. The gate enforces the vocabulary whether or not it has been reviewed; review decides whether the vocabulary should be trusted, not whether it is enforced.",
    "",
    "## How to review",
    "",
    "For each entry, read the sentence as a user would read it next to its report, then answer: (1) Is it true for **every** report for which its conditions hold? (2) Does it assert, or imply, anything about geography, time, cause, legal status or scientific validity that the GeoImpact-CI report cannot support? (3) If it is a disclaimer, is the negation accurate against the cited contract text shown? (4) Is any `{{slot}}` rendered with the right label and unit? Record *Approve*, *Reject* or *Change*, your name and the date. Only after every entry is decided may `review.status` in `approved-skeletons.json` be changed, by the reviewer, together with `reviewed_by` and `reviewed_on`.",
    "",
    "Automated flags are keyword hints for where to look. An absent flag does not mean a sentence is safe, and a present flag does not mean it is wrong.",
    "",
    "- `affirmative`: the sentence states something. Check it against the report.",
    "- `disclaimer`: the sentence is negated (\"no\", \"not\", \"cannot\"). Check the negation against the cited contract text.",
    "- `geographic`, `temporal`, `causal`, `legal`, `scientific`: the constant text contains a word from that area. **Any affirmative sentence flagged here is an unsupported interpretation unless the report field supporting it is named.**",
    "",
    "## Slot fields (label and unit rendered by the gate)",
    "",
    ...[...new Set(Object.values(registry.claims).flat().flatMap((entry) => [...entry.skeleton.matchAll(/\{\{([^}]+)\}\}/g)].map((match) => match[1])))].sort().map((id) => `- \`${id}\`: ${slotLabel(id)}`),
    "",
    "## Entries",
    ""
  ];
  let counter = 0;
  for (const [claimId, entries] of Object.entries(registry.claims)) {
    for (const entry of entries) {
      counter += 1;
      const { flags, negated } = flagsFor(entry.skeleton);
      const kind = negated ? "disclaimer" : "affirmative";
      const cited = [...(sources.get(`${claimId}\u0000${entry.skeleton}`)?.values() ?? [])];
      lines.push(`### R${String(counter).padStart(2, "0")} \`${claimId}\``, "");
      lines.push(`> ${entry.skeleton}`, "");
      lines.push(`- Conditions: ${entry.when?.length ? entry.when.map((name) => `\`${name}\``).join(", ") : "none (unconditional)"}`);
      lines.push(`- Flags: \`${kind}\`${flags.length ? `, ${flags.map((flag) => `\`${flag}\``).join(", ")}` : ""}`);
      if (cited.length) {
        lines.push("- Contract text this sentence relies on:");
        for (const reference of cited) lines.push(`  - \`${reference.source_id}#${reference.fact_key}\`: ${reference.value}`);
      } else {
        lines.push("- Contract text this sentence relies on: none cited. The sentence is the application's own wording.");
      }
      lines.push("- [ ] True for every report meeting the conditions", "- [ ] No unsupported geographic, temporal, causal, legal or scientific interpretation", "- [ ] Negation (if any) matches the cited contract text", "- [ ] Slots carry the right label and unit", "- Decision (Approve / Reject / Change): ________  Reviewer: ________  Date: ________", "");
    }
  }
  lines.push(`Total entries: ${counter}.`, "");
  return lines.join("\n");
}

if (process.argv[1] && fileURLToPath(import.meta.url) === fileURLToPath(new URL(`file://${process.argv[1].replaceAll("\\", "/")}`))) {
  const text = await buildChecklist();
  if (process.argv.includes("--check")) {
    const current = await readFile(outputUrl, "utf8").catch(() => "");
    if (current !== text) {
      process.stderr.write("The review checklist is out of date; run node geoimpact-copilot/semantic/build-review-checklist.mjs.\n");
      process.exitCode = 1;
    } else {
      process.stdout.write("Review checklist matches the vocabulary.\n");
    }
  } else {
    await writeFile(outputUrl, text);
    process.stdout.write(`Wrote ${fileURLToPath(outputUrl)}\n`);
  }
}
