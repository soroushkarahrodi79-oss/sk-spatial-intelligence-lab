// Validates data/evidence-catalog.json and keeps its embedded copy in space/index.html in sync.
//   node scripts/evidence-catalog.mjs            check (offline, deterministic)
//   node scripts/evidence-catalog.mjs --write    re-embed the catalog into space/index.html
//   node scripts/evidence-catalog.mjs --online   also request every source URL (network)
import assert from "node:assert/strict";
import { existsSync } from "node:fs";
import { readFile, writeFile } from "node:fs/promises";
import Ajv2020 from "ajv/dist/2020.js";

const catalogPath = "data/evidence-catalog.json";
const pagePath = "space/index.html";
const markerStart = "<!-- evidence-catalog:start (generated by scripts/evidence-catalog.mjs; edit data/evidence-catalog.json) -->";
const markerEnd = "<!-- evidence-catalog:end -->";
const searchGateMinimum = 6;

const catalogSource = await readFile(catalogPath, "utf8");
const catalog = JSON.parse(catalogSource);
const schema = JSON.parse(await readFile("data/evidence-catalog.schema.json", "utf8"));

function embeddedBlock() {
  // "<" is escaped so catalog text can never close the script element.
  const json = JSON.stringify(catalog).replace(/</g, "\\u003c");
  return `${markerStart}\n<script type="application/json" id="evidence-catalog">${json}</script>\n${markerEnd}`;
}

if (process.argv.includes("--write")) {
  const page = await readFile(pagePath, "utf8");
  const pattern = new RegExp(`${markerStart.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}[\\s\\S]*?${markerEnd}`);
  assert.match(page, pattern, "index.html must contain the evidence-catalog markers");
  await writeFile(pagePath, page.replace(pattern, () => embeddedBlock()));
  console.log("Embedded evidence catalog into space/index.html");
  process.exit(0);
}

function report(label) {
  console.log(`PASS ${label}`);
}

// 1. Schema
const ajv = new Ajv2020({ allErrors: true, strict: true });
const validate = ajv.compile(schema);
assert.ok(validate(catalog), `Catalog schema errors: ${ajv.errorsText(validate.errors)}`);
report(`catalog matches schema (${catalog.records.length} records)`);

const records = catalog.records;
const byId = new Map(records.map((record) => [record.id, record]));
const prefix = { "geoimpact-ci": "GIC", "madrid-lens": "MUL", salmas: "SAL", lab: "LAB" };

// 2. Identity and duplicates
assert.equal(byId.size, records.length, "Evidence IDs must be unique");
for (const field of [(r) => r.title.en, (r) => r.title.es, (r) => r.finding.en, (r) => r.question.en]) {
  const values = records.map((record) => field(record).trim().toLowerCase());
  assert.equal(new Set(values).size, values.length, "Duplicate evidence text detected");
}
const sourceKeys = records.map((record) => JSON.stringify(record.sources.map((s) => s.url).sort()));
assert.equal(new Set(sourceKeys).size, sourceKeys.length, "Two records cite exactly the same source set");
for (const record of records) {
  assert.ok(record.id.includes(`-${prefix[record.project]}-`), `${record.id}: ID prefix must match project ${record.project}`);
  assert.ok(catalog.pins[record.project], `${record.id}: project ${record.project} needs a pinned revision`);
}
report("unique IDs, no duplicate titles, findings, questions or source sets, ID prefixes match projects");

// 3. Sources: pinned, traceable, internal paths exist
for (const record of records) {
  const pinsOfProject = catalog.pins[record.project];
  assert.ok(record.sources.some((source) => source.role === "evidence"), `${record.id}: needs at least one evidence source`);
  for (const source of record.sources) {
    if (source.pin.startsWith("run:")) {
      assert.ok(source.url.endsWith(`/actions/runs/${source.pin.slice(4)}`), `${record.id}: run pin does not match URL`);
      continue;
    }
    const match = source.url.match(/^https:\/\/github\.com\/([^/]+\/[^/]+)\/blob\/([0-9a-f]{40})\/(.+)$/);
    assert.ok(match, `${record.id}: source must be a commit-pinned blob URL: ${source.url}`);
    assert.equal(match[2], source.pin, `${record.id}: source pin must equal the SHA in its URL`);
    const projectOwnsRepo = Object.values(catalog.pins).some((pin) => pin.repo === match[1]);
    assert.ok(projectOwnsRepo, `${record.id}: source repository ${match[1]} is not one of the catalog's pinned repositories`);
    if (match[1] === pinsOfProject.repo) assert.equal(match[2], pinsOfProject.sha, `${record.id}: source SHA differs from the project's pinned revision`);
    if (match[1] === catalog.pins.lab.repo) {
      assert.ok(existsSync(decodeURIComponent(match[3])), `${record.id}: internal path does not exist: ${match[3]}`);
    }
  }
}
report("every source is commit-pinned or a fixed CI run, pins match the catalog, internal paths exist");

// 4. Status semantics: dimensions stay separate and consistent with the data origin
for (const record of records) {
  const { status, dataOrigin } = record;
  if (dataOrigin === "synthetic") assert.equal(status.scientificValidation, "synthetic-only", `${record.id}: synthetic evidence must be labelled synthetic-only`);
  if (status.scientificValidation === "synthetic-only") assert.equal(dataOrigin, "synthetic", `${record.id}: synthetic-only is reserved for synthetic data`);
  if (["hold", "pending"].includes(status.scientificValidation)) {
    assert.ok(record.hold, `${record.id}: hold or pending scientific validation requires an explicit hold statement`);
  }
  if (status.reproducibility === "receipt-only") assert.ok(record.relatedTo.length > 0, `${record.id}: a receipt must reference the case it inspects`);
  for (const related of record.relatedTo) {
    assert.ok(byId.has(related) && related !== record.id, `${record.id}: relatedTo references unknown or own ID ${related}`);
  }
}
report("synthetic and real-source evidence stay distinct; HOLD and pending states are explicit");

// 5. Unsupported scientific claims and private data
const overclaim = /\b(validated|verified|certified|proven|proves|proof|ground[- ]truth|guarantee[sd]?|accurate|accuracy of|independently (validated|reviewed)|AI-generated)\b/i;
for (const record of records) {
  for (const field of ["title", "finding"]) {
    for (const language of ["en", "es"]) {
      const text = record[field][language];
      assert.doesNotMatch(text, overclaim, `${record.id}.${field}.${language} uses overclaiming language: ${text.match(overclaim)?.[0]}`);
      assert.doesNotMatch(text, /\b(validad[oa]s?|verificad[oa]s?|certificad[oa]s?|demostrad[oa]s?|prueba que)\b/i, `${record.id}.${field}.${language} uses overclaiming language`);
    }
  }
}
const everything = JSON.stringify(catalog);
assert.doesNotMatch(everything, /[\w.+-]+@[\w-]+\.[\w.-]+/, "Catalog must not contain e-mail addresses");
assert.doesNotMatch(everything, /\b(hf_[A-Za-z0-9]{20,}|sk-[A-Za-z0-9]{20,}|ghp_[A-Za-z0-9]{20,})\b/, "Catalog must not contain token-shaped strings");
assert.doesNotMatch(everything, /-?\d{1,3}\.\d{4,}\s*[,;]\s*-?\d{1,3}\.\d{4,}/, "Catalog must not contain coordinate pairs");
report("no overclaiming wording in titles or findings, no e-mail, token or coordinate patterns");

// 6. Search gate: interactive search is justified only with enough distinct records
const projects = new Set(records.map((record) => record.project));
const types = new Set(records.map((record) => record.type));
assert.ok(records.length >= searchGateMinimum, `Search gate not met: ${records.length} < ${searchGateMinimum} records`);
assert.ok(projects.size >= 2 && types.size >= 2, "Filters need at least two distinct projects and evidence types");
report(`search gate GO: ${records.length} records, ${projects.size} projects, ${types.size} evidence types`);

// 7. Embedded copy in the page matches the catalog
const page = await readFile(pagePath, "utf8");
assert.ok(page.includes(embeddedBlock()), "space/index.html embeds a stale evidence catalog. Run: npm run build:evidence");
report("space/index.html embeds the current catalog byte for byte");

// 8. Optional: every source answers
if (process.argv.includes("--online")) {
  const urls = [...new Set(records.flatMap((record) => record.sources.map((source) => source.url)))];
  const failures = [];
  await Promise.all(urls.map(async (url) => {
    try {
      const response = await fetch(url, { method: "HEAD", redirect: "follow", signal: AbortSignal.timeout(20000), headers: { "user-agent": "SK-Spatial-Intelligence-Lab-Evidence-Check/0.1" } });
      if (!response.ok) failures.push(`${url}: HTTP ${response.status}`);
    } catch (error) {
      failures.push(`${url}: ${error.message}`);
    }
  }));
  assert.equal(failures.length, 0, failures.join("\n"));
  report(`all ${urls.length} evidence source URLs responded successfully`);
}
